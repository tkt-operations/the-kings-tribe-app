import { describe, expect, it, vi } from "vitest";

vi.mock("server-only", () => ({}));
const { isPublicAddress } = await import("@/lib/product/ip-policy");

describe("isPublicAddress", () => {
  it.each([
    "0.0.0.0", "0.1.2.3", "10.0.0.1", "100.64.0.1", "100.127.255.255", "127.0.0.1", "127.255.255.254",
    "169.254.169.254", "169.254.0.1", "172.16.0.1", "172.31.255.255", "192.0.0.1", "192.0.2.10", "192.88.99.1",
    "192.168.1.1", "198.18.0.1", "198.19.255.255", "198.51.100.7", "203.0.113.9", "224.0.0.1", "239.255.255.250",
    "240.0.0.1", "255.255.255.255",
    "::", "::1", "::ffff:127.0.0.1", "::ffff:10.0.0.1", "::ffff:8.8.8.8", "64:ff9b::7f00:1", "fc00::1", "fd12:3456::1",
    "fe80::1", "ff02::1", "2001::1", "2001:db8::1", "2002:7f00:1::1",
    "not-an-ip", "", "1.2.3",
  ])("blocks %s", (address) => {
    expect(isPublicAddress(address)).toBe(false);
  });

  it.each(["8.8.8.8", "1.1.1.1", "23.45.67.89", "172.32.0.1", "100.128.0.1", "2606:4700:4700::1111", "2a00:1450:4001::200e"])(
    "allows public %s",
    (address) => {
      expect(isPublicAddress(address)).toBe(true);
    },
  );
});
